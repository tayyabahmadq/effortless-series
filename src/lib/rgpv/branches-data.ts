export const rgpvBranchCount = 40;
export const rgpvSubjectCount = 1502;

export function getRgpvBranch(slug: string): RgpvBranch | undefined {
  return rgpvBranches.find((b) => b.slug === slug);
}

export function findRgpvSubject(
  branchSlug: string,
  semester: number,
  subjectSlug: string
): { branch: RgpvBranch; subject: RgpvSubject } | undefined {
  const branch = getRgpvBranch(branchSlug);
  if (!branch) return undefined;
  const sem = branch.semesters.find((s) => s.number === semester);
  if (!sem) return undefined;
  const subject = sem.subjects.find((s) => s.slug === subjectSlug);
  if (!subject) return undefined;
  return { branch, subject };
}
